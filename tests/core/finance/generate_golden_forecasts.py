def build_golden_entry(case: dict[str, Any]) -> dict[str, Any]:
    fi = FinancialInputs.model_validate(case["financial_inputs"])
    insights = ListingInsights.model_validate(case["insights"]) if case.get("insights") else None
    forecast = run_financial_model(fi, horizon_years=case["horizon_years"], insights=insights)
    return {
        "description": case["description"],
        "forecast": forecast.model_dump(mode="json"),
    }


def compute_matrix() -> dict[str, Any]:
    cases: dict[str, Any] = {}
    for case in CASES:
        cases[case["id"]] = build_golden_entry(case)
    return cases


# ---------------------------------------------------------------------------
# The safety gate: classify a diff between the currently-committed `cases` subtree and a freshly
# computed one as structural, content-drifting, both, or neither.
# ---------------------------------------------------------------------------


@dataclass
class DiffReport:
    structural_notes: list[str] = field(default_factory=list)
    content_notes: list[str] = field(default_factory=list)  # "case::path: detail (rel=...)"
    max_float_rel_drift: float = 0.0

    @property
    def is_empty(self) -> bool:
        return not self.structural_notes and not self.content_notes

    @property
    def is_structural_only(self) -> bool:
        return bool(self.structural_notes) and not self.content_notes


def classify_diff(old_cases: dict[str, Any], new_cases: dict[str, Any]) -> DiffReport:
    report = DiffReport()

    old_ids, new_ids = set(old_cases.keys()), set(new_cases.keys())
    if old_ids != new_ids:
        removed = sorted(old_ids - new_ids)
        added = sorted(new_ids - old_ids)
        if removed:
            report.structural_notes.append(f"case(s) removed: {removed}")
        if added:
            report.structural_notes.append(f"case(s) added: {added}")

    for case_id in sorted(old_ids & new_ids):
        old_forecast = old_cases[case_id]["forecast"]
        new_forecast = new_cases[case_id]["forecast"]
        # `expected` = the currently-committed golden, `actual` = the freshly-computed matrix --
        # deliberately the SAME direction golden_tolerance.compare_golden is used in the harness,
        # so "structural" and "content drift" here mean exactly what they mean there.
        cmp = compare_golden(case_id, actual=new_forecast, expected=old_forecast)
        for d in cmp.structural:
            report.structural_notes.append(f"{case_id}::{d.path}: {d.detail}")
        for d in cmp.exact_mismatches + cmp.zero_violations:
            report.content_notes.append(f"{case_id}::{d.path}: {d.kind.value} ({d.detail}) -- anchored={d.expected!r} new={d.actual!r}")
        for d in cmp.approaching + cmp.exceeding:
            rel = d.rel_drift or 0.0
            report.content_notes.append(
                f"{case_id}::{d.path}: {d.kind.value}, rel_drift={rel:.4e} -- anchored={d.expected!r} new={d.actual!r}"
            )
            if rel > report.max_float_rel_drift:
                report.max_float_rel_drift = rel
        # Deviations that DO NOT reach the DeviationKind.APPROACHING floor (i.e. silently pass
        # under the tolerance rule) are, correctly, not diff-worthy here either -- the whole point
        # of the tolerance rule is that such drift never triggers a regeneration (D.3 section 3.4).

    return report


def _refusal_message(report: DiffReport) -> str:
    lines = [
        "REFUSING TO REGENERATE.",
        "",
    ]
    if report.content_notes:
        lines.append(f"{len(report.content_notes)} pre-existing field(s) changed value:")
        for note in report.content_notes[:25]:
            lines.append(f"    {note}")
        if len(report.content_notes) > 25:
            lines.append(f"    ... and {len(report.content_notes) - 25} more")
        lines.append("")
    if report.structural_notes:
        lines.append("Structural change(s) are ALSO present in this diff (this is exactly the")
        lines.append("bundling GD.1 condition C3 forbids -- a structural regeneration must not")
        lines.append("also co-carry numeric drift without review):")
        for note in report.structural_notes:
            lines.append(f"    {note}")
        lines.append("")
    lines.append(
        "In-tolerance drift is NEVER a reason to re-anchor -- that is the ratchet this harness "
        "exists to prevent. If a number genuinely changed for a reason, that reason is a "
        "correctness decision: re-run with "
        '--supersede-anchor --rationale "<why>" --approved-by "<name>" '
        "and expect it to be reviewed as one."
    )
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument(
        "--supersede-anchor", action="store_true", help="Allow writing tests/data/golden/ANCHOR.json (the ONLY way it is ever written)."
    )
    parser.add_argument(
        "--rationale", type=str, default="", help="Required with --supersede-anchor: why this drift/change is a reviewed, correct decision."
    )
    parser.add_argument(
        "--approved-by", type=str, default="", help="Required with --supersede-anchor: the founder's name (GD.1 condition C3)."
    )
    parser.add_argument(
        "--commit", type=str, default="", help="Optional: the commit SHA this regeneration lands in (fill in after committing if omitted)."
    )
    args = parser.parse_args()

    new_cases = compute_matrix()

    old_golden: dict[str, Any] = {"_meta": "", "cases": {}}
    if OUT_PATH.exists():
        with OUT_PATH.open("r", encoding="utf-8") as f:
            old_golden = json.load(f)

    diff = classify_diff(old_golden.get("cases", {}), new_cases)

    if args.supersede_anchor:
        if not args.rationale.strip():
            print('ERROR: --supersede-anchor requires --rationale "<why>".', file=sys.stderr)
            sys.exit(2)
        if not args.approved_by.strip():
            print('ERROR: --supersede-anchor requires --approved-by "<name>" (GD.1 condition C3).', file=sys.stderr)
            sys.exit(2)
        if diff.is_empty:
            print("No change detected -- nothing to supersede. ANCHOR.json and the golden file are untouched.")
            return

        _write_golden(new_cases)
        previous_anchor = load_anchor(ANCHOR_PATH) if ANCHOR_PATH.exists() else None
        new_anchor = {
            "anchored_artifact": "finance_engine_forecasts.json",
            "cases_sha256": canonical_cases_digest(new_cases),
            "anchored_at_commit": args.commit or "PENDING -- fill in the commit SHA once this change is committed",
            "anchored_on": date.today().isoformat(),
            "approved_by": args.approved_by,
            "rationale": args.rationale,
            "max_rel_drift_vs_previous_anchor": diff.max_float_rel_drift,
            "supersedes": previous_anchor,
        }
        with ANCHOR_PATH.open("w", encoding="utf-8") as f:
            json.dump(new_anchor, f, indent=2, sort_keys=True)
            f.write("\n")
        print(f"Wrote {len(new_cases)} golden case(s) to {OUT_PATH}")
        print(f"Superseded ANCHOR.json: max_rel_drift_vs_previous_anchor={diff.max_float_rel_drift:.4e}")
        print("")
        print("REMINDER (GD.1 condition C3): add a dated regeneration record to")
        print("tests/core/finance/test_golden_forecasts.py's module docstring, in the existing")
        print("REGENERATION RECORD format, before this is merged. This script does not write")
        print("that narrative for you -- see the PV.5 and Gate V records for the expected shape.")
        if not args.commit:
            print("Also fill in ANCHOR.json::anchored_at_commit with the real commit SHA once committed.")
        return

    # Bare run.
    if diff.is_empty:
        print("Up to date -- no structural or content change detected. Nothing written.")
        return

    if diff.content_notes:
        print(_refusal_message(diff))
        sys.exit(1)

    # Structural-only: safe to write the golden (no pre-existing field's value moved), but the
    # anchor is now stale by construction and must be re-anchored explicitly.
    _write_golden(new_cases)
    print(f"Wrote {len(new_cases)} golden case(s) to {OUT_PATH} (STRUCTURAL-ONLY change).")
    print("")
    print("Structural change(s) detected (no pre-existing field's value moved):")
    for note in diff.structural_notes:
        print(f"    {note}")
    print("")
    print("tests/data/golden/ANCHOR.json was NOT updated -- a numeric anchor cannot exist for a")
    print("field that did not exist, but the digest still moved, so test_golden_anchor.py will")
    print("now (correctly) fail until you re-run with:")
    print("    python -m tests.core.finance.generate_golden_forecasts --supersede-anchor \\")
    print('        --rationale "<why this structural change is correct>" --approved-by "<name>"')


def _write_golden(cases: dict[str, Any]) -> None:
    goldens: dict[str, Any] = {"_meta": _META_BANNER, "cases": cases}
    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    with OUT_PATH.open("w", encoding="utf-8") as f:
        json.dump(goldens, f, indent=2, sort_keys=True)
        f.write("\n")


if __name__ == "__main__":
    main()
